const { buildSync } = require('esbuild')
const { strict: assert } = require('node:assert')
const vm = require('node:vm')
const output = buildSync({ entryPoints: ['src/domain/production.ts'], bundle: true, platform: 'node', format: 'cjs', write: false })
const context = { module: { exports: {} }, exports: {} }
vm.runInNewContext(output.outputFiles[0].text, context)
const { geometry, checkMachine, findMachine, planSheet, finishingLines, productionRoutes, evaluateRoute, drawingMeasurements } = context.module.exports
const box = { design: '0201', profile: 'B', lengthMm: 300, widthMm: 200, heightMm: 150, hasPrinting: false, creaseLevel: 'same', printType: 'digital', printColors: 1 }
const inline = geometry(box, 'inline', '')
const staggered = drawingMeasurements(geometry({...box,profile:'BF',creaseLevel:'different'},'rotary',''))
assert.equal(staggered.slots[0].offset,3.5)
assert.equal(staggered.slots[0].topLeft,105.5)
assert.equal(staggered.slots[0].topRight,102)
assert.equal(staggered.slots[0].topDepth,105.5)
assert.equal(staggered.panels[0].body,154)
assert.equal(staggered.panels[1].body,161)
assert.equal(drawingMeasurements(geometry(box,'rotary','')).slots[0].offset,0)
const openTop=drawingMeasurements(geometry({...box,design:'0200',profile:'BF',creaseLevel:'different'},'rotary',''))
assert.equal(openTop.slots[0].topDepth,0)
assert.equal(openTop.slots[0].bottomDepth,105.5)
assert.equal(openTop.slots[0].offset,3.5)
assert.equal(inline.slot, 8)
assert.equal(inline.width, 1043)
assert.equal(inline.height, 355)
assert.equal(planSheet(inline,findMachine('tcy-5pa')).sheetX,inline.width+8)
assert.equal(geometry({...box,lengthMm:596},'inline','').flap,35, 'Exactly 1600 mm of panels keeps a 35 mm flap')
assert.equal(geometry({...box,lengthMm:597},'inline','').flap,40, 'More than 1600 mm of panels requires a 40 mm flap')
assert.equal(geometry({...box,profile:'E'},'flatbed','').flap,30)
assert.equal(geometry({...box,profile:'F'},'flatbed','').flap,30)
assert.equal(geometry(box,'flatbed','').flap,35)
assert.equal(geometry(box,'rotary','').flap,35)
assert.equal(geometry({...box,profile:'E'},'rotary','').flap,30)
for (const tech of ['rotary','plotter']) {
  for (const profile of ['BF','BE','BD','BC']) assert.equal(geometry({...box,profile},tech,'').flap,40)
  for (const profile of ['D','B','C']) assert.equal(geometry({...box,profile},tech,'').flap,35)
  for (const profile of ['F','E']) assert.equal(geometry({...box,profile},tech,'').flap,30)
  assert.equal(geometry({...box,design:'0201-2',profile:'BC'},tech,'godswill-gts-3000').flap,45)
}
assert.equal(geometry({...box,profile:'BC'},'flatbed','').flap,35)
for (const profile of ['BF','BE','BD','BC']) {
  for (const line of ['ward','kongsberg']) {
    for (const finishing of ['signature-elite-135','rolam-1100','rito-jh-1700']) {
      assert(!evaluateRoute({...box,profile},line,finishing).blocked.some(reason=>reason.includes('Соединительный клапан')), 'All folder gluers must accept the 40 mm five-layer flap')
    }
  }
}
assert.equal(geometry({...box,design:'0201-2'},'flatbed','godswill-gts-3000').flap,45)
const compoundBox={...box,lengthMm:500,widthMm:300,heightMm:250,design:'0201-4',creaseLevel:'different'}
const quarters=geometry(compoundBox,'rotary','godswill-gts-3000')
assert.equal(quarters.parts.length,2)
assert.equal(quarters.count,4)
assert.equal(quarters.parts[0].quantity,2)
assert.equal(quarters.parts[1].quantity,2)
assert.equal(quarters.parts[0].geometry.panels[0],503)
assert.equal(quarters.parts[1].geometry.panels[0],303)
assert.equal(quarters.parts[0].geometry.flap,45)
assert.equal(quarters.parts[1].geometry.flap,45)
assert.equal(quarters.width,quarters.parts[0].geometry.width+quarters.parts[1].geometry.width)
assert(evaluateRoute(compoundBox,'ward','godswill-gts-3000').blocked.length===0)
const separate=evaluateRoute(compoundBox,'ward','godswill-gts-3000')
assert.equal(separate.sheet,null)
assert.equal(separate.partSheets.length,2)
assert(separate.partSheets.every(part=>part.sheet && part.geometry.panels.length===1))
assert(evaluateRoute(compoundBox,'ward','signature-elite-135').blocked.length>0)
const halves=geometry({...compoundBox,design:'0201-2'},'rotary','gofrotime-sdj-2000b')
assert.equal(halves.count,2)
assert.equal(halves.panels[0],501)
assert.equal(halves.panels[1],303)
assert.equal(geometry({ ...box, profile: 'BC' }, 'inline', '').slot, 10)
assert.equal(geometry(box, 'flatbed', '').slot, 6)
assert.equal(geometry(box, 'rotary', '').slot, 6)
assert.equal(geometry(box, 'plotter', 'godswill-gts-3000').flap, 45)
const fullOverlapBox={...box,design:'0203',creaseLevel:'different'}
const fullOverlap=geometry(fullOverlapBox,'flatbed','signature-elite-135')
assert.equal(fullOverlap.height,558)
assert.equal(fullOverlap.width,1043)
const fullOverlapDimensions=drawingMeasurements(fullOverlap)
assert.equal(fullOverlapDimensions.panels[0].top,103.5)
assert.equal(fullOverlapDimensions.panels[1].top,200)
assert.equal(fullOverlapDimensions.panels[1].bottom,200)
assert.equal(fullOverlapDimensions.slots[0].offset,2.5)
assert.equal(fullOverlapDimensions.slots[0].topDepth,202.5)
assert(fullOverlap.points.every(([x,y])=>x>=0 && x<=fullOverlap.width && y>=0 && y<=fullOverlap.height))
assert(evaluateRoute(fullOverlapBox,'ward','signature-elite-135').blocked.length===0)
assert(evaluateRoute(fullOverlapBox,'tcy-5pa','').blocked.some(reason=>reason.includes('Конструкция')))
assert(evaluateRoute({...fullOverlapBox,creaseLevel:'same'},'ward','signature-elite-135').blocked.some(reason=>reason.includes('разных уровнях')))
assert.equal(geometry({ ...box, widthMm: 400 }, 'inline', ''), null)
assert(checkMachine(findMachine('tcy-5pa'), { ...box, profile: 'F' }, inline, 'inline').blocked.some(reason => reason.includes('Профиль')))
assert(checkMachine(findMachine('tcy-5pa'), { ...box, creaseLevel: 'different' }, inline, 'inline').blocked.some(reason => reason.includes('Биговки')))
assert(checkMachine(findMachine('tcy-5pa'), { ...box, hasPrinting: true, printType: 'flexo', printColors: 3 }, inline, 'inline').blocked.some(reason => reason.includes('Печать')))
assert(checkMachine(findMachine('signature-elite-135'), box, geometry(box, 'flatbed', ''), 'folderGluer').review.length > 0)
const dieBlank = geometry(box, 'rotary', '')
const ward = findMachine('ward')
const wardPlan = planSheet(dieBlank, ward)
assert(wardPlan, '300×200×150 must have a feasible WARD layout')
assert(wardPlan.count > 1, 'WARD must use multiple blanks rather than reject one short blank')
assert.equal(wardPlan.count, 3)
assert(wardPlan.sheetY >= 560)
assert(wardPlan.sheetX <= 2460 && wardPlan.sheetY <= 1549)
assert.equal(checkMachine(ward, box, dieBlank, 'rotary').blocked.length, 0)
assert(checkMachine(ward,box,{ ...dieBlank,height:299 },'rotary').blocked.some(reason=>reason.includes('Паллетизация')))
assert(!checkMachine(ward,box,{ ...dieBlank,height:300 },'rotary').blocked.some(reason=>reason.includes('Паллетизация')))
const smallBox={ ...box,lengthMm:150,widthMm:100,heightMm:70 }
const smallBlank=geometry(smallBox,'rotary','')
assert(planSheet(smallBlank,ward), 'Small blank can fit a multi-up sheet')
assert(checkMachine(ward,smallBox,smallBlank,'rotary').blocked.some(reason=>reason.includes('Паллетизация')), 'Multi-up must not bypass individual blank minimum')
const withPinlong = planSheet(dieBlank, ward, findMachine('pinlong'))
assert(withPinlong && withPinlong.sheetY <= 840)
assert.equal(withPinlong.count, 2)
const oversized = geometry({ ...box, lengthMm: 1300, widthMm: 1200 }, 'rotary', '')
assert.equal(planSheet(oversized, ward), null)
assert(checkMachine(ward, { ...box, lengthMm: 1300, widthMm: 1200 }, oversized, 'rotary').blocked.length > 0)
assert.equal(checkMachine(findMachine('signature-elite-135'),box,dieBlank,'folderGluer',wardPlan).blocked.length,0, 'Folder gluer receives individual blanks, not the die sheet')
assert(finishingLines(box,'ward').every(line=>!line.id.startsWith('godswill') && !line.id.startsWith('gofrotime')))
assert(finishingLines(box,'kongsberg').some(line=>line.id==='manual-gluing'))
assert(!finishingLines(box,'ward').some(line=>line.id==='manual-gluing'))
assert(finishingLines({...box,design:'0201-2'},'ward').every(line=>line.id.startsWith('godswill') || line.id.startsWith('gofrotime')))
assert(evaluateRoute(box,'ward','godswill-gts-3000').blocked.some(reason=>reason.includes('Сшивка')))
const flexoRoutes=productionRoutes({...box,hasPrinting:true,printType:'flexo',printColors:3})
assert(flexoRoutes.some(route=>route.line.id==='asahi'))
assert(flexoRoutes.find(route=>route.line.id==='asahi').blocked.some(reason=>reason.includes('Печать')))
assert(flexoRoutes.find(route=>route.line.id==='ward').blocked.length===0)
const digitalRoutes=productionRoutes({...box,hasPrinting:true,printType:'digital'})
assert(digitalRoutes.filter(route=>!route.blocked.length).every(route=>route.line.id==='kongsberg' && route.selection.printing==='digital'))
assert(digitalRoutes.find(route=>route.line.id==='asahi').blocked.some(reason=>reason.includes('только на плоттере')))
assert(checkMachine(ward,{...box,profile:'E'},dieBlank,'rotary').blocked.some(reason=>reason.includes('Профиль E')))
assert(productionRoutes({...box,hasPrinting:true,printType:'pinlong'}).every(route=>!route.line.id.startsWith('tcy') && route.selection.printing==='pinlong'))
assert(productionRoutes(box).some(route=>route.line.id==='ward' && route.sheet.count===3 && !route.blocked.length))
assert(productionRoutes({...box,widthMm:400}).every(route=>route.blocked.length))
console.log('Production geometry, complete routes and equipment checks passed')
